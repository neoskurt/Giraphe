function buildTickets(): Ticket[] {
  resetTicketIdCounter(100)
  const orderByStatus: Record<string, number> = {}

  return SPECS.map((spec) => {
    const order = orderByStatus[spec.status] ?? 0
    orderByStatus[spec.status] = order + 1

    const createdAt = daysAgo(spec.createdDaysAgo)
    const updatedAt = daysAgo(spec.updatedDaysAgo)
    const dueDate = spec.dueDaysOffset === null ? null : daysFromNow(spec.dueDaysOffset)

    return {
      id: nextTicketId(),
      title: spec.title,
      description: spec.description,
      type: spec.type,
      team: spec.team,
      tags: spec.tags,
      priority: spec.priority,
      status: spec.status,
      assigneeId: spec.assigneeId,
      creatorId: spec.creatorId,
      dueDate: dueDate ? dueDate.toISOString() : null,
      createdAt: createdAt.toISOString(),
      updatedAt: updatedAt.toISOString(),
      order,
    }
  })
}

export const tickets: Ticket[] = buildTickets()
